import {
  copyFileSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmdirSync,
  statSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';

/**
 * Keeping ComfyUI's copy of comfyllama the same as Latent's.
 *
 * comfyllama is vendored here so the two can be changed together — but ComfyUI
 * loads it from its own `custom_nodes`, so a change made here reached ComfyUI
 * only when somebody copied it across by hand, and until then Latent asked for
 * nodes and inputs the running ComfyUI did not have. The Supervisor calls this
 * just before it starts ComfyUI, which is the one moment the copy can change
 * without pulling files out from under a running process.
 *
 * Three things it will not touch, because each is somebody else's arrangement:
 * a link to this very folder (already current), a git checkout of its own
 * (updated with git, and a copy over it would leave it dirty), and a ComfyUI
 * with no `custom_nodes` at all (a wrong root, more likely than a fresh one).
 */

/** Written into a copy this made, so later runs know the whole folder is theirs. */
export const MANAGED_MARKER = '.latent-managed';

/** Not part of what ComfyUI loads, or regenerated by Python on its own. */
const SKIPPED_DIRS = new Set(['tests', '__pycache__', '.git', 'node_modules', '.pytest_cache']);
const isSkippedFile = (name: string) => name.endsWith('.pyc') || name === '.DS_Store';

export interface SyncResult {
  action: 'installed' | 'updated' | 'unchanged' | 'skipped';
  /** `<custom_nodes>/comfyllama`, or null when there was nowhere to put it. */
  target: string | null;
  /** One sentence for the service's log. */
  message: string;
  /** Files written or removed. */
  changed: string[];
}

/**
 * ComfyUI's `custom_nodes`, from the folder setting or else the service's root.
 *
 * The setting is the ComfyUI folder itself (the one with `main.py`). A
 * service's root is that folder too, except on the Windows portable build,
 * where it is the folder around it with `python_embeded` beside `ComfyUI`.
 */
export function customNodesDir(comfyRoot: string | null, serviceRoot: string): string | null {
  const candidates = comfyRoot?.trim()
    ? [resolve(comfyRoot.trim())]
    : [resolve(serviceRoot, 'ComfyUI'), resolve(serviceRoot)];
  for (const root of candidates) {
    const dir = join(root, 'custom_nodes');
    if (existsSync(dir) && statSync(dir).isDirectory()) return dir;
  }
  return null;
}

/** Every file under `root` that belongs in ComfyUI's copy, as relative paths. */
function listFiles(root: string, at = ''): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(join(root, at), { withFileTypes: true })) {
    const path = at ? join(at, entry.name) : entry.name;
    if (entry.isDirectory()) {
      if (SKIPPED_DIRS.has(entry.name)) continue;
      out.push(...listFiles(root, path));
    } else if (entry.isFile() && !isSkippedFile(entry.name) && entry.name !== MANAGED_MARKER) {
      out.push(path);
    }
  }
  return out;
}

const sameBytes = (a: string, b: string) => {
  if (!existsSync(b)) return false;
  if (statSync(a).size !== statSync(b).size) return false;
  return readFileSync(a).equals(readFileSync(b));
};

/**
 * Bring `<customNodes>/comfyllama` up to `source`.
 *
 * Only changed files are written. Files the source no longer has are removed
 * only from a copy this made — one carrying `MANAGED_MARKER` — so a copy put
 * there by hand loses nothing the first time it is taken over.
 */
export function syncComfyllama(source: string, customNodes: string | null): SyncResult {
  if (!customNodes) {
    return {
      action: 'skipped',
      target: null,
      message:
        'comfyllama not updated: no custom_nodes folder found. Check Settings → Servers → the ' +
        'ComfyUI folder (the one with main.py in it).',
      changed: [],
    };
  }
  const target = join(customNodes, 'comfyllama');

  if (existsSync(target) || isLink(target)) {
    if (isLink(target) || sameDir(target, source)) {
      return {
        action: 'skipped',
        target,
        message: `comfyllama is linked to Latent's copy at ${target}; nothing to update.`,
        changed: [],
      };
    }
    if (existsSync(join(target, '.git'))) {
      return {
        action: 'skipped',
        target,
        message:
          `comfyllama not updated: ${target} is its own git checkout. Update it with ` +
          '"git pull", or delete it and Latent will keep a copy there itself.',
        changed: [],
      };
    }
  }

  const fresh = !existsSync(target);
  const managed = existsSync(join(target, MANAGED_MARKER));
  const wanted = listFiles(source);
  const changed: string[] = [];

  for (const path of wanted) {
    const from = join(source, path);
    const to = join(target, path);
    if (sameBytes(from, to)) continue;
    mkdirSync(dirname(to), { recursive: true });
    copyFileSync(from, to);
    changed.push(path);
  }

  if (managed) {
    const keep = new Set(wanted);
    for (const path of listFiles(target)) {
      if (keep.has(path)) continue;
      unlinkSync(join(target, path));
      changed.push(`${path} (removed)`);
      removeEmptyParents(target, dirname(join(target, path)));
    }
  }

  writeFileSync(
    join(target, MANAGED_MARKER),
    "Kept the same as Latent's comfyllama each time Latent starts ComfyUI.\n" +
      'Files here that Latent does not have are removed. To manage this folder\n' +
      'yourself, delete this file — or replace the folder with a git clone.\n',
  );

  const requirements = changed.some((path) => path === 'requirements.txt');
  const action = fresh ? 'installed' : changed.length > 0 ? 'updated' : 'unchanged';
  const message =
    action === 'installed'
      ? `comfyllama installed in ${target} (${changed.length} files).`
      : action === 'updated'
        ? `comfyllama updated in ${target}: ${changed.length} file(s) changed.`
        : 'comfyllama is up to date.';
  return {
    action,
    target,
    message: requirements
      ? `${message} ${fresh ? 'Install its requirements' : 'Its requirements changed: install them'} ` +
        `with ComfyUI's Python, "python -m pip install -r ${join(target, 'requirements.txt')}".`
      : message,
    changed,
  };
}

function isLink(path: string): boolean {
  try {
    return lstatSync(path).isSymbolicLink();
  } catch {
    return false;
  }
}

function sameDir(a: string, b: string): boolean {
  try {
    return realpathSync(a) === realpathSync(b);
  } catch {
    return false;
  }
}

/** Remove now-empty folders between `dir` and `root`, never `root` itself. */
function removeEmptyParents(root: string, dir: string): void {
  let current = dir;
  while (current !== root && current.startsWith(root + sep) && relative(root, current) !== '') {
    try {
      if (readdirSync(current).length > 0) return;
      rmdirSync(current);
    } catch {
      return;
    }
    current = dirname(current);
  }
}
